<#
.SYNOPSIS
  Writes the SBOM (CycloneDX 1.5 JSON) and the third-party notices for a published build
  (specification 17.3: license list and SBOM).

.DESCRIPTION
  Reads <PublishDir>\D2Translator.App.deps.json, which lists exactly what the self-contained
  build ships (NuGet packages and runtime packs), and looks up each package's nuspec and license
  files in the local NuGet cache. Writes:
    <OutDir>\sbom.cdx.json
    <OutDir>\THIRD-PARTY-NOTICES.md
  Nothing is downloaded. Hashes are the SHA-512 of the .nupkg as recorded by NuGet.

.EXAMPLE
  powershell -File scripts\generate-sbom.ps1 -PublishDir artifacts\msix\layout -OutDir artifacts\msix
#>
param(
    [Parameter(Mandatory)] [string] $PublishDir,
    [Parameter(Mandatory)] [string] $OutDir,
    [string] $AppVersion = "0.1.0"
)

$ErrorActionPreference = "Stop"

$depsPath = Join-Path $PublishDir "D2Translator.App.deps.json"
if (-not (Test-Path $depsPath)) { throw "deps.json not found: $depsPath" }
$packagesRoot = if ($env:NUGET_PACKAGES) { $env:NUGET_PACKAGES } else { Join-Path $env:USERPROFILE ".nuget\packages" }
New-Item -ItemType Directory -Force $OutDir | Out-Null

function ConvertTo-Hex([string] $base64) {
    $bytes = [Convert]::FromBase64String($base64)
    return -join ($bytes | ForEach-Object { $_.ToString("x2") })
}

$deps = Get-Content $depsPath -Raw -Encoding UTF8 | ConvertFrom-Json
$components = New-Object System.Collections.Generic.List[object]
$notices = New-Object System.Collections.Generic.List[string]
$mitOnly = New-Object System.Collections.Generic.List[string]

foreach ($library in $deps.libraries.PSObject.Properties | Sort-Object Name) {
    $type = $library.Value.type
    if ($type -eq "project") { continue }

    $name, $version = $library.Name -split "/", 2
    $id = $name -replace "^runtimepack\.", ""
    $folder = Join-Path $packagesRoot (Join-Path $id.ToLowerInvariant() $version)
    $nuspecPath = Join-Path $folder ($id.ToLowerInvariant() + ".nuspec")
    if (-not (Test-Path $nuspecPath)) { throw "nuspec not found in the NuGet cache: $nuspecPath" }

    [xml] $nuspec = Get-Content $nuspecPath -Raw -Encoding UTF8
    $meta = $nuspec.package.metadata
    $license = $null
    if ($meta.license -and $meta.license.type -eq "expression") { $license = $meta.license.'#text' }
    $licenseUrl = if ($license) { "https://licenses.nuget.org/$license" } else { $meta.licenseUrl }
    $projectUrl = $meta.projectUrl
    $copyright = $meta.copyright

    $sha = if ($library.Value.sha512) { $library.Value.sha512 -replace "^sha512-", "" } else {
        $shaFile = Join-Path $folder ($id.ToLowerInvariant() + "." + $version + ".nupkg.sha512")
        if (Test-Path $shaFile) { (Get-Content $shaFile -Raw).Trim() } else { $null }
    }

    $component = [ordered]@{
        type = "library"
        name = $id
        version = $version
        purl = "pkg:nuget/$id@$version"
    }
    if ($sha) { $component.hashes = @(@{ alg = "SHA-512"; content = (ConvertTo-Hex $sha) }) }
    if ($license) { $component.licenses = @(@{ expression = $license }) }
    elseif ($licenseUrl) { $component.licenses = @(@{ license = @{ name = "See URL"; url = $licenseUrl } }) }
    if ($projectUrl) { $component.externalReferences = @(@{ type = "website"; url = $projectUrl }) }
    $components.Add($component)

    $notices.Add("## $id $version")
    $notices.Add("")
    $notices.Add("- License: " + $(if ($license) { $license } else { "see $licenseUrl" }))
    if ($projectUrl) { $notices.Add("- Project: $projectUrl") }
    if ($copyright) { $notices.Add("- Copyright: $copyright") }
    $notices.Add("")

    $licenseFiles = Get-ChildItem $folder -File | Where-Object { $_.Name -match '^(license|licence)(\.(txt|md))?$' }
    if ($licenseFiles) {
        foreach ($file in $licenseFiles) {
            $notices.Add('```text')
            $notices.Add((Get-Content $file.FullName -Raw -Encoding UTF8).TrimEnd())
            $notices.Add('```')
            $notices.Add("")
        }
    }
    elseif ($license -eq "MIT") {
        $mitOnly.Add("$id $version")
        $notices.Add("The package does not include a license file. The standard MIT License text below applies, with the copyright notice above.")
        $notices.Add("")
    }
}

$header = @(
    "# Third-party notices",
    "",
    "D2 Chat Translator $AppVersion is licensed under the MIT License (see LICENSE).",
    "The self-contained build includes the following components. Generated by scripts/generate-sbom.ps1 from D2Translator.App.deps.json.",
    ""
)
$footer = @()
if ($mitOnly.Count -gt 0) {
    $footer = @(
        "## Standard MIT License text",
        "",
        '```text',
        "Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated documentation files (the ""Software""), to deal in the Software without restriction, including without limitation the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is furnished to do so, subject to the following conditions:",
        "",
        "The above copyright notice and this permission notice shall be included in all copies or substantial portions of the Software.",
        "",
        "THE SOFTWARE IS PROVIDED ""AS IS"", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.",
        '```',
        ""
    )
}

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllLines((Join-Path $OutDir "THIRD-PARTY-NOTICES.md"), [string[]]($header + $notices + $footer), $utf8)

$bom = [ordered]@{
    bomFormat = "CycloneDX"
    specVersion = "1.5"
    serialNumber = "urn:uuid:" + [guid]::NewGuid().ToString()
    version = 1
    metadata = [ordered]@{
        timestamp = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
        tools = @(@{ name = "scripts/generate-sbom.ps1" })
        component = [ordered]@{
            type = "application"
            name = "D2 Chat Translator"
            version = $AppVersion
            licenses = @(@{ license = @{ id = "MIT" } })
            externalReferences = @(@{ type = "vcs"; url = "https://github.com/KANABUNN/D2-Translator" })
        }
    }
    components = $components
}
[System.IO.File]::WriteAllText((Join-Path $OutDir "sbom.cdx.json"), ($bom | ConvertTo-Json -Depth 8), $utf8)
Write-Host "SBOM: $($components.Count) components -> $OutDir"
